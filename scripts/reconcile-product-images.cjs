/* Explicitly reviewed exterior media only. Never infer equivalence from a code alias. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8').replace(/^\uFEFF/, '');
const decisions = JSON.parse(read('docs/catalog-completion/image-decisions.json'));
const catalog = JSON.parse(read('docs/catalog-completion/catalog-draft.json')).products;
const prior = JSON.parse(read('docs/catalog-completion/media-review-findings.json'));
const context = {window:{SAHAND_PRODUCTS:{}}};
vm.createContext(context);
for (const name of fs.readdirSync(path.join(root, 'data/products')).filter(n=>n.endsWith('.js'))) {
  vm.runInContext(read('data/products/'+name), context, {timeout:1000});
}
const live = context.window.SAHAND_PRODUCTS;
const mappings = {};
for (const [code, d] of Object.entries(decisions)) {
  if (d.decision !== 'use') continue;
  if (prior[code]) throw new Error('Unresolved earlier rejection: '+code);
  if (!catalog.some(p=>p.code===code) || !fs.existsSync(path.join(root,d.src))) throw new Error('Missing identity or image: '+code);
  mappings[code] = {src:d.src, name:d.name};
}
const payload = `/* Generated by scripts/reconcile-product-images.cjs; reviewed exterior images, not X-rays. */
(function(){
  const map=${JSON.stringify(mappings)};
  const root=new URL('../',document.currentScript.src);
  window.SAHAND_REVIEWED_IMAGES=map;
  function apply(){
  for(const [code,entry] of Object.entries(map)){
    const p=window.SAHAND_PRODUCTS?.[code];if(!p)continue;
    const url=new URL(entry.src,root).href;
    p.media=p.media||{};
    p.media.images=[url,...(p.media.images||[]).filter(x=>x!==url)];
    p.images=p.media.images.slice();
    if(p.title)p.title.fa=entry.name;
  }
  }
  apply();
  document.addEventListener('DOMContentLoaded',()=>{
    apply();
    if(window.SAHAND_PRODUCTS){
      window.renderAllProducts?.('all');
      window.dispatchEvent(new HashChangeEvent('hashchange'));
    }
  },{once:true});
  const embedded=document.getElementById('product-data');
  if(embedded){
    const products=JSON.parse(embedded.textContent);
    for(const p of products){const entry=map[p.code];if(entry){p.images=[new URL(entry.src,root).href,...(p.images||[]).filter(x=>!x.endsWith(entry.src))];}}
    embedded.textContent=JSON.stringify(products);
  }
})();
`;
fs.writeFileSync(path.join(root,'data/reviewed-product-images.js'),payload,'utf8');
const pages=['index.html','preview-experiments/site.html',...fs.readdirSync(root).filter(n=>/^preview-\d+$/.test(n)).map(n=>n+'/index.html')];
const integrations=[];
for(const file of pages){
  if(!fs.existsSync(path.join(root,file)))continue;
  let html=read(file);
  const hasBase=/<base\s/i.test(html);
  const src=(hasBase||file==='index.html'?'':'../')+'data/reviewed-product-images.js?v=media-review-1';
  const tag=`<script src="${src}"></script>`;
  if(html.includes('data/reviewed-product-images.js')){integrations.push(file);continue;}
  if(/<script src="runtime\/app\.js[^\"]*"><\/script>/.test(html)){
    html=html.replace(/<script src="runtime\/app\.js[^\"]*"><\/script>/,m=>tag+'\n'+m);
  }else if(html.includes("const products=JSON.parse(document.getElementById('product-data').textContent)")){
    html=html.replace(/<script>\s*'use strict';/,tag+"\n<script>\n'use strict';");
  }else continue;
  fs.writeFileSync(path.join(root,file),html,'utf8');integrations.push(file);
}
const now=new Date();
const rows=catalog.map(p=>{
  const d=decisions[p.code],old=live[p.code]?.media?.images||[],studio=p.visuals?.studio;
  return {code:p.code,name:p.name,candidate:studio?.src||null,exists:!!studio?.src&&fs.existsSync(path.join(root,studio.src)),previousImages:old,
    decision:d?.decision||(prior[p.code]?'hold':'pending'),reason:d?.reason||prior[p.code]?.reason||'Awaiting side-by-side visual review; inherited visualReview flag is not sufficient.',
    identityScope:studio?.identityScope||'',sharedWith:catalog.filter(q=>q.code!==p.code&&q.visuals?.studio?.src===studio?.src).map(q=>q.code)};
});
const report={updatedAt:now.toISOString(),tehranTime:new Intl.DateTimeFormat('fa-IR',{timeZone:'Asia/Tehran',dateStyle:'full',timeStyle:'long'}).format(now),
  counts:{products:rows.length,connected:Object.keys(mappings).length,hold:rows.filter(p=>p.decision==='hold').length,pending:rows.filter(p=>p.decision==='pending').length},
  integrations,excludedPages:pages.filter(p=>!integrations.includes(p)),deployment:'Local build; live deployment must be verified separately',products:rows};
fs.writeFileSync(path.join(root,'status/image-reconciliation.json'),JSON.stringify(report,null,2)+'\n','utf8');
console.log(JSON.stringify({counts:report.counts,integrations,excludedPages:report.excludedPages}));